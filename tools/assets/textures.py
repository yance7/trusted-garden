"""Deterministic, seamless material authoring. No downloaded texture inputs."""
from pathlib import Path
import json
import numpy as np
from PIL import Image

OUT = Path(__file__).resolve().parents[2] / 'public' / 'assets' / 'textures'
OUT.mkdir(parents=True, exist_ok=True)
REV = 'hd-materials-11'
marker = OUT / 'manifest.json'
if marker.exists() and json.loads(marker.read_text()).get('revision') == REV:
    print('Textures current')
    raise SystemExit(0)

families = ['concrete', 'wood', 'soil', 'bark', 'leaf', 'metal', 'grass', 'turf']
manifest = {'revision': REV, 'source': 'Original deterministic procedural materials; generated by textures.py', 'families': {}}
for idx, family in enumerate(families):
    n = 2048 if family in ['grass', 'turf'] else 4096
    rng = np.random.default_rng(8810 + idx)
    x, y = np.meshgrid(np.arange(n, dtype=np.float32)/n, np.arange(n, dtype=np.float32)/n)
    def noise(size):
        # Periodic source grid makes mip-level edges continuous.
        a = rng.random((size, size)).astype(np.float32)
        a = np.pad(a, ((0,1),(0,1)), mode='wrap')
        return np.asarray(Image.fromarray(a).resize((n,n),Image.Resampling.BICUBIC)).astype(np.float32)
    broad, fine = noise(36), noise(384)
    h = broad*.15 + fine*.025
    if family == 'wood': h = .25*np.sin(y*2*np.pi*72 + np.sin(x*2*np.pi*3)*1.8 + broad*2) + fine*.06
    elif family == 'soil': h = broad*.30 + noise(110)*.25 + fine*.15
    elif family == 'bark': h = np.power(np.abs(np.sin(x*2*np.pi*37 + broad*5)),3)*.7 + fine*.12
    elif family == 'leaf':
        spine = np.exp(-np.square((x-.5)*75))
        veins = np.power(np.maximum(0,np.cos((y+np.abs(x-.5)*.55)*2*np.pi*24)),18)
        h = spine*.4 + veins*.12 + broad*.03
    elif family == 'grass':
        blades = np.zeros((n,n),dtype=np.float32); blade_id = np.zeros((n,n),dtype=np.int16); bh = np.full((n,n),.06,dtype=np.float32)
        for k in range(110):
            x0 = .06 + rng.random()*.88; hk = .30 + rng.random()*.70; ck = (rng.random()-.5)*.5; wk = .010 + rng.random()*.020
            cx = x0 + ck*np.square(y/hk); inside = (y < hk) & (np.abs(x-cx) < wk*(1-.65*y/hk))
            blades = np.where(inside, np.maximum(blades, 1.0 - y/hk*.25), blades); blade_id = np.where(inside, k+1, blade_id); bh = np.where(inside, hk, bh)
        h = blades*.5 + fine*.02
    elif family == 'turf':
        # Opaque mown turf on a 2 m tile: blade rows near 16 cm, mown bands near 60 cm.
        rows = np.sin(y*2*np.pi*12 + np.sin(x*2*np.pi*3)*1.1)*.5+.5
        cols = np.sin(x*2*np.pi*3 + np.sin(y*2*np.pi*2)*1.0)*.5+.5
        h = rows*.07 + cols*.06 + noise(48)*.24 + fine*.06
    elif family == 'metal': h = fine*.006 + .008*np.sin(x*2*np.pi*96)
    dx, dy = np.gradient(h)
    strength = {'wood':16,'soil':30,'bark':35,'leaf':25,'metal':4,'concrete':12,'grass':18,'turf':14}[family]
    normal = np.stack([-dx*strength, -dy*strength, np.ones_like(h)],axis=2)
    normal /= np.linalg.norm(normal,axis=2,keepdims=True)
    normal = ((normal*.5+.5)*255).clip(0,255).astype(np.uint8)
    grain = .84 + (h-h.mean())*.30 + (fine-.5)*.06
    color = np.stack([grain*1.0,grain*.99,grain*.96],axis=2)
    alpha = np.ones((n,n),dtype=np.float32)
    if family == 'metal': color[:]=.93+(fine[...,None]-.5)*.015
    if family == 'leaf':
        # Luminance-neutral detail tile: per-object material colors keep their hue,
        # while the alpha silhouette and veins carry the leaf shape.
        half = np.power(np.maximum(0,np.sin(np.pi*np.power(y,.85))),.7)*.44
        half *= 1 - .12*np.power(np.maximum(0,np.sin(y*2*np.pi*46)),8)
        alpha = np.clip((half - np.abs(x-.5))*240 + .5, 0, 1)
        shade = .90 + broad*.10 - np.abs(x-.5)*.10
        color = np.stack([shade*.97, shade, shade*.90],axis=2)
        color += np.exp(-np.square((x-.5)*60))[...,None]*np.array([.08,.09,.06])
        color += np.power(np.maximum(0,np.cos((y+np.abs(x-.5)*.55)*2*np.pi*24)),18)[...,None]*np.array([.06,.07,.04])
        color *= (1 - .18*np.power(np.maximum(0,1-y*14),2))[...,None]
    if family == 'grass':
        alpha = np.clip(blades*5,0,1)
        tints = .78 + rng.random(112)*.44
        tint = tints[blade_id][...,None]
        t = np.clip(y/np.maximum(bh,.06),0,1)[...,None]
        color = (np.array([.09,.17,.06])*(1-t) + np.array([.41,.56,.24])*t)*tint
    if family == 'turf':
        tint = .84 + noise(24)*.26
        color = np.stack([(.17+rows*.05+cols*.03)*tint, (.31+rows*.07+cols*.05)*tint, (.11+rows*.03)*tint],axis=2)
    color=(color*255).clip(0,255).astype(np.uint8)
    rough={'wood':.76,'soil':.96,'bark':.91,'leaf':.63,'metal':.5,'concrete':.88,'grass':.68,'turf':.9}[family]
    orm=np.stack([np.clip(.97-(h-h.min())*.09,.75,1),np.clip(rough+(fine-.5)*.13,.08,1),np.ones_like(h)],axis=2)
    files={}
    for kind,array in [('color',color),('normal',normal),('orm',(orm*255).astype(np.uint8))]:
        if kind=='color' and family in ('leaf','grass'):
            img=Image.fromarray(np.dstack([array,(alpha*255).astype(np.uint8)]),'RGBA')
        else:
            img=Image.fromarray(array,'RGB')
        if kind=='orm' and family in ('leaf','metal','grass'):img=img.resize((n//2,n//2),Image.Resampling.LANCZOS)
        path=OUT/f'{family}-{kind}.webp'
        img.save(path,format='WEBP',quality=94 if kind=='color'else 98,method=4)
        files[kind]={'url':f'textures/{path.name}','width':img.width,'height':img.height,'bytes':path.stat().st_size}
    if family=='concrete':
        # Re-evaluate at higher resolution, rather than upscaling a finished image.
        N=4096; xx,yy=np.meshgrid(np.arange(N,dtype=np.float32)/N,np.arange(N,dtype=np.float32)/N)
        detail=.88+.016*np.sin(xx*2*np.pi*731)*np.sin(yy*2*np.pi*613)+.022*np.sin(xx*2*np.pi*79+np.sin(yy*2*np.pi*13))
        rgb=np.stack([detail,detail*.995,detail*.985],axis=2)
        img=Image.fromarray((rgb*255).clip(0,255).astype(np.uint8),'RGB');path=OUT/'concrete-color-4k.webp';img.save(path,quality=91,method=4)
        files['color4k']={'url':f'textures/{path.name}','width':N,'height':N,'bytes':path.stat().st_size}
        del xx,yy,detail,rgb,img
    manifest['families'][family]=files
    print(f'Material {family}:',sum(f['bytes']for f in files.values()))
marker.write_text(json.dumps(manifest,indent=2),encoding='utf-8')
